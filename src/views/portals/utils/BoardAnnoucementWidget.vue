<template>
  <div v-show="hasAnnouncement && !hidden" class="publication has-background-info has-text-white no-print">
    <div class="section is-info">
      <button class="delete" @click="hide" />
      <div ref="content" />
    </div>
  </div>
</template>

<script>
import forum from '@/js/apis/forum';
import { sanitizeHtml } from '@/js/sanitize-html';
import { getPreferences } from '@/js/vue-plugins/local-storage';

// stored under the component name, as before: existing preferences are kept
const preferences = getPreferences('BoardAnnouncementWidget');

export default {
  name: 'BoardAnnouncementWidget',

  data() {
    return {
      hasAnnouncement: false,
      hidden: false,
      updatedAt: null,
    };
  },

  computed: {
    readdenPostKey: {
      get() {
        return preferences.get('readdenPostKey');
      },
      set(value) {
        preferences.set('readdenPostKey', value);
      },
    },
  },

  created() {
    this.loadBoardAnnouncement();
  },

  methods: {
    loadBoardAnnouncement() {
      forum
        .readBoardAnnouncement()
        .then(({ topic, post }) => {
          if (forum.hasTag(topic, 'visible')) {
            this.updatedAt = post.updated_at;

            if (this.readdenPostKey === post.updated_at) {
              return;
            }

            this.hasAnnouncement = true;

            // post.cooked is HTML generated by the forum from a user's post: sanitize it
            // before injecting it in the DOM to prevent stored XSS.
            const content = document.createElement('div');
            content.innerHTML = sanitizeHtml(post.cooked);
            this.$refs.content.appendChild(content);
          }
        })
        .catch((error) => {
          console.error('Error retrieving board announcement :', error);
        });
    },

    hide() {
      this.hidden = true;
      this.readdenPostKey = this.updatedAt;
    },
  },
};
</script>

