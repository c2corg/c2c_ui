<template>
  <div v-if="isNormalView" class="box no-print">
    <h2 class="title is-2" v-translate>Comments</h2>

    <div v-if="document.disable_comments">
      <p v-translate>Comments are disabled.</p>
    </div>

    <div v-else-if="promise && promise.error" class="notification is-danger">
      <p>
        <span v-translate>Oups! Something went wrong with forum. Here is the message :</span>
        <br />
        {{ (promise.error as Error).message }}
      </p>
    </div>

    <div v-else>
      <div v-for="post of comments" :key="post.id" class="discourse-post">
        <div class="columns is-gapless">
          <div class="column is-narrow discourse-post-avatar">
            <img
              :src="getAvatarUrl(post)"
              alt="Avatar"
              :style="'width:' + forumAvatarSize + 'px;height:' + forumAvatarSize + 'px'"
              loading="lazy"
            />
          </div>
          <div class="column">
            <div class="discourse-post-header">
              <a
                :href="forum.url + '/u/' + post.username"
                :title="post.username"
                class="discourse-post-header-username"
              >
                {{ post.username }}
              </a>
              <span class="is-pulled-right">
                {{ $dateUtils.timeAgo(post['created_at']) }}
              </span>
            </div>

            <!-- eslint-disable-next-line vue/no-v-html -->
            <div class="discourse-content" v-html="post.cooked" />
          </div>
        </div>
      </div>

      <div class="has-text-centered">
        <login-button v-if="!$user.isLogged" key="not-logged" v-translate>Log in to post a comment</login-button>

        <!-- API bug with first comment creation? -->
        <button
          v-else-if="locale.topic_id === null"
          key="no-topic"
          class="button is-primary"
          @click="createTopic"
          :disabled="!isProduction"
          v-translate
        >
          Post the first comment
        </button>

        <!-- Only the system comment exists -->
        <a
          v-else-if="comments.length === 0"
          key="no-comment"
          :href="discussionUrl"
          class="button is-primary"
          v-translate
        >
          Post the first comment
        </a>
        <a v-else-if="allCommentDisplayed" key="all-displayed" :href="discussionUrl" class="button is-primary">
          <span v-translate>Continue the discussion</span>
        </a>
        <a v-else key="some-displayed" :href="discussionUrl" class="button is-primary">
          <span v-translate>View next comments and continue the discussion</span>
        </a>
      </div>
    </div>
  </div>
</template>

<script setup lang="ts">
import { computed, ref } from 'vue';

import type { ApiData } from '@/js/apis/BaseApi';
import c2c from '@/js/apis/c2c';
import forum from '@/js/apis/forum';
import { useViewMode } from '@/js/composables/view-mode';
import config from '@/js/config';
import { documentProperty } from '@/js/properties';
import { sanitizeHtml } from '@/js/sanitize-html';

// a post of the topic of the document, as the box reads it
type Post = { id: number; name: string; username: string; avatar_template: string; created_at: string; cooked: string };

const isProduction = config.urls.name === 'prod';
const forumAvatarSize = 45;

const computeCooked = function (cooked: string) {
  cooked = cooked.replace(/<a class="mention" href="/g, '<a class="mention" href="' + forum.url);

  // post.cooked is HTML generated by the Discourse forum from a user's post:
  // sanitize it before it gets bound with v-html, to prevent stored XSS.
  return sanitizeHtml(cooked);
};

const props = defineProps({ ...documentProperty });

const { isNormalView } = useViewMode();

const promise = ref<ApiData | { data?: undefined; error?: undefined }>({});

const locale = computed(() => props.document.cooked);

const topic = computed(() => promise.value.data);

const discussionUrl = computed(() => {
  if (!topic.value) {
    return undefined;
  }

  return forum.url + '/t/' + topic.value.slug + '/' + locale.value.topic_id + '/' + topic.value.posts_count;
});

const comments = computed(() => {
  const result: Post[] = [];

  if (!topic.value || !topic.value.post_stream) {
    return result;
  }

  const data = topic.value.post_stream;

  let posts: Post[] = data.posts;

  if (posts[0].name === 'system') {
    posts = posts.slice(1);
  }

  // copy the posts: mutating the reactive topic here would invalidate this computed again, and the
  // mention links would get the forum url prepended on each evaluation, in an endless render loop
  for (const post of posts) {
    result.push({ ...post, cooked: computeCooked(post.cooked) });
  }

  return result;
});

const allCommentDisplayed = computed(() => {
  if (!topic.value || !topic.value.post_stream || !topic.value.posts_count) {
    return true;
  }
  return topic.value.post_stream.posts.length >= topic.value.posts_count;
});

function createTopic() {
  const document_id = props.document.document_id!;
  const lang = locale.value.lang;

  // create topic must go through c2c API, because system has to create
  // first message with good link
  c2c.forum
    .createTopic(document_id, lang)
    .then((response) => {
      const topic_id = response['data']['topic_id'];
      const url = forum.url + '/t/' + document_id + '_' + lang + '/' + topic_id;
      window.location.href = url;
    })
    .catch((error) => {
      // the answer of the API, when the topic exists already
      const response = (error as { response?: { status: number; data: { errors: { topic_id?: number }[] } } }).response;
      if (response && response.status === 400) {
        const topic_id = response['data']['errors'][0]['topic_id'];
        if (topic_id !== undefined) {
          locale.value.topic_id = topic_id;
          getComments();
        }
      }
    });
}

function getComments() {
  if (locale.value.topic_id) {
    promise.value = forum.getTopic(locale.value.topic_id);
  }
}

function getAvatarUrl(user: Post) {
  return forum.getAvatarUrl(user, forumAvatarSize);
}

getComments();
</script>

